"""Copy rules for the repository's own prose (docs, READMEs, workflows, templates).

The rules come from GOAL.md and docs/COVERAGE.md: never "every country"; the one
rounded claim is "190+ jurisdictions"; exactly two quality states, named
"Accountant-reviewed" (tier 1) and "Checked against the law" / "Sourced from the law"
(tier 2; "Source-cited draft" is retired); and the retired role and state
words ("Partner", "attest", "verified accountant", "accountant-verified",
"Accountant-authored") do not come back.

Scope: every tracked Markdown file except CHANGELOG.md (history keeps its old
wording), docs/research/ and ledgers/ (source quotations and historical evidence),
and the skill content trees
(skills/, packages/, agent-skills/<slug>/, plugins/openaccountants/skills/),
which are tax content rather than repository copy and are regenerated by the
sync; those are governed by scripts/validate-guides.py.
"""

from __future__ import annotations

import re
import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

EXCLUDED_FILES = {"CHANGELOG.md"}
EXCLUDED_PREFIXES = (
    "docs/research/",
    "ledgers/",
    "skills/",
    "packages/",
    "plugins/openaccountants/skills/",
)
# agent-skills/<slug>/SKILL.md is generated content; agent-skills/README.md and
# agent-skills/LICENSE.md are repository copy and stay in scope.
AGENT_SKILL_CONTENT = re.compile(r"^agent-skills/[^/]+/")

RULES = [
    ("every country", re.compile(r"every country", re.IGNORECASE)),
    ("Partner as a role word", re.compile(r"\bPartner\b")),
    ("attest", re.compile(r"attest", re.IGNORECASE)),
    ("verified accountant", re.compile(r"verified accountant", re.IGNORECASE)),
    ("accountant-verified", re.compile(r"accountant-verified", re.IGNORECASE)),
    ("Accountant-authored as a state", re.compile(r"Accountant-authored")),
    (
        "a rounded jurisdiction count other than 190+",
        re.compile(r"\b(1[0-8]\d|[2-9]\d\d)\+ jurisdictions"),
    ),
]


def tracked_markdown() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "*.md"], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout
    files = []
    for rel in out.splitlines():
        if rel in EXCLUDED_FILES or rel.startswith(EXCLUDED_PREFIXES):
            continue
        if AGENT_SKILL_CONTENT.match(rel):
            continue
        files.append(rel)
    return files


class CopyRulesTest(unittest.TestCase):
    def test_scope_is_not_empty(self) -> None:
        files = tracked_markdown()
        self.assertIn("README.md", files)
        self.assertIn("docs/QUALITY-TIERS.md", files)
        self.assertNotIn("CHANGELOG.md", files)
        self.assertNotIn("ledgers/fo-individual-income-tax.md", files)
        self.assertNotIn("ledgers/faroe-islands-2026-evidence/ledgers/pit-evidence/frozen-guide.md", files)

    def test_repository_copy_follows_the_rules(self) -> None:
        violations: list[str] = []
        for rel in tracked_markdown():
            text = (ROOT / rel).read_text(encoding="utf-8")
            for lineno, line in enumerate(text.splitlines(), 1):
                for name, pattern in RULES:
                    if pattern.search(line):
                        violations.append(f"{rel}:{lineno}: {name}: {line.strip()[:120]}")
        self.assertEqual(
            violations, [], "copy rule violations:\n" + "\n".join(violations)
        )


if __name__ == "__main__":
    unittest.main()
