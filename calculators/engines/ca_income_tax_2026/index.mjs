/** JSON with object keys sorted at every level, so key order never changes the hash. */
function canonicalJson(value) {
	if (value === null || typeof value !== "object") return JSON.stringify(value) ?? "null";
	if (Array.isArray(value)) return `[${value.map((v) => canonicalJson(v === void 0 ? null : v)).join(",")}]`;
	const obj = value;
	return `{${Object.keys(obj).filter((k) => obj[k] !== void 0).sort().map((k) => `${JSON.stringify(k)}:${canonicalJson(obj[k])}`).join(",")}}`;
}
/** id = sha256(engine name, engine version, canonical facts, canonical result), newline-joined. */
function receiptId(engine, version, facts, result) {
	return createHash("sha256").update([
		engine,
		version,
		canonicalJson(facts),
		canonicalJson(result)
	].join("\n")).digest("hex");
}

