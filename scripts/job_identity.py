#!/usr/bin/env python3
"""What job a skill does, so one job in one jurisdiction has one skill.

A skill may declare `job:` in its frontmatter (a short kebab id). Otherwise the job
comes from the slug: country code and name out, year and short numeric suffixes
out, then the synonym families below. See docs/skill-template.md, rule 6.
"""

from __future__ import annotations

import json
import os
import re

DATA_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "jurisdictions.json")

#: Everyday names the jurisdiction table does not carry.
EXTRA_NAMES = {
    "GB": ("uk", "united-kingdom", "great-britain"),
    "US": ("usa", "united-states"),
    "AE": ("uae", "united-arab-emirates"),
    "NL": ("the-netherlands",),
    "CZ": ("czech-republic", "czechia"),
}

#: Whole jobs that mean the same work. Add a line only when two wordings are the same return.
JOB_FAMILIES = {
    "vat-gst": ("vat", "gst", "vat-gst", "gst-vat", "vat-return", "gst-return", "vat-returns", "gst-returns",
                "vat-gst-return", "vat-filing", "gst-filing"),
    "payroll": ("payroll", "paye", "payroll-return", "payroll-tax", "payroll-taxes"),
    "income-tax": ("income-tax", "income-tax-return", "personal-income-tax", "personal-income-tax-return",
                   "individual-income-tax", "individual-income-tax-return", "personal-tax", "pit"),
    "corporate-tax": ("corporate-tax", "corporate-tax-return", "corporate-income-tax",
                      "corporate-income-tax-return", "corporation-tax", "corporation-tax-return",
                      "company-tax", "company-tax-return", "company-income-tax", "cit"),
}
FAMILY_OF = {member: family for family, members in JOB_FAMILIES.items() for member in members}

_YEAR_SUFFIX = re.compile(r"-(?:(?:ty|fy)?(?:19|20)\d\d(?:-\d\d(?:\d\d)?)?|[2-9])$")


def kebab(text):
    return re.sub(r"[^a-z0-9]+", "-", str(text or "").lower()).strip("-")


def load_jurisdiction_words(path=DATA_PATH):
    """{code: (prefixes, names)}. A prefix goes only at the start, a name anywhere."""
    with open(path, encoding="utf-8") as fh:
        rows = json.load(fh)
    words = {}
    for row in rows:
        code = row["code"].upper()
        names = {kebab(re.sub(r"\(.*?\)", "", row.get("name") or "")), *EXTRA_NAMES.get(code, ())}
        if row.get("dir"):
            names.add(kebab(os.path.basename(row["dir"])))
        names.discard("")
        prefixes = {kebab(code), *(kebab(p) for p in code.split("-"))}
        words[code] = (sorted(prefixes, key=len, reverse=True), sorted(names, key=len, reverse=True))
    return words


def strip_place(slug, code, words):
    """The slug with its country prefix, country name and year or numeric suffix gone."""
    prefixes, names = words.get(str(code or "").upper(), ((), ()))
    text = kebab(slug)
    changed = True
    while changed:
        changed = False
        for name in names:
            wrapped = re.sub(rf"(?:^|-){re.escape(name)}(?=-|$)", "", f"-{text}").strip("-")
            if wrapped and wrapped != text:
                text, changed = wrapped, True
        for prefix in prefixes:
            if text.startswith(prefix + "-"):
                text, changed = text[len(prefix) + 1:], True
        trimmed = _YEAR_SUFFIX.sub("", text)
        if trimmed and trimmed != text:
            text, changed = trimmed, True
    return text


def family(job):
    return FAMILY_OF.get(job, job)


def identity(guide, words):
    """(job, stripped slug, stripped name) of an index row carrying an optional `job`."""
    code = guide.get("jurisdiction")
    slug_name = strip_place(guide["slug"], code, words)
    declared = kebab(guide.get("job"))
    job = family(declared or slug_name)
    return job, slug_name, strip_place(guide.get("name") or guide["slug"], code, words)


def same_job(a, b, words):
    """True when two skills in one jurisdiction do the same job, or their stripped names match."""
    job_a, slug_a, name_a = identity(a, words)
    job_b, slug_b, name_b = identity(b, words)
    return job_a == job_b or bool({slug_a, name_a} & {slug_b, name_b})


def same_job_groups(guides, words, skip_codes=()):
    """{(code, job): [guides]} for every job held by two or more slugs. A slug counts
    once, so a copy under packages/ is not a duplicate of its source under skills/."""
    groups = {}
    for guide in guides:
        code = str(guide.get("jurisdiction") or "").upper()
        if code and code not in skip_codes:
            rows = groups.setdefault((code, identity(guide, words)[0]), {})
            rows.setdefault(guide["slug"], guide)
    return {key: list(rows.values()) for key, rows in sorted(groups.items()) if len(rows) > 1}


def render_report(groups):
    lines = [
        "# Skills doing the same job",
        "",
        "Generated by `python3 scripts/validate-guides.py --duplicates-report`. Do not edit by hand.",
        "",
        "Each group is two or more skills in one jurisdiction with the same job (docs/skill-template.md, "
        "rule 6). Existing groups only warn. A pull request that adds or renames a skill into a group fails. "
        "Skills that really do different work declare `job:` in their frontmatter and leave the report.",
        "",
        f"{len(groups)} groups, {sum(len(rows) for rows in groups.values())} skills.",
        "",
        "| Jurisdiction | Job | Skills |",
        "|---|---|---|",
    ]
    for (code, job), rows in groups.items():
        slugs = ", ".join(f"`{row['slug']}`" for row in sorted(rows, key=lambda r: r["slug"]))
        lines.append(f"| {code} | {job} | {slugs} |")
    return "\n".join(lines) + "\n"
