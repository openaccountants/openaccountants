#!/usr/bin/env python3
"""Write skills/COUNTRIES.md: the directory of every country pack.

Region, country, state (scripts/coverage-report.py), owner (scripts/data/jurisdictions.json),
number of skills, how many are on the current tax year, and how many an accountant has
reviewed. Read from the skill files, so it never needs editing by hand. Run again after skills change:

    python3 scripts/build-country-index.py
"""
import collections
import importlib.util
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
YEAR = "2026"
REGIONS = [("europe", "Europe"), ("americas", "Americas"), ("apac", "Asia-Pacific"),
           ("middle-east", "Middle East"), ("africa", "Africa")]
OWNERS = {"michael": "Michael Cutajar", "jeff": "Jeff Watts", "ryan": "Ryan Duguid"}
# Display names that the title-cased registry name gets wrong.
NAMES = {"AE": "United Arab Emirates", "CW": "Curaçao", "ST": "São Tomé and Príncipe", "GB": "United Kingdom"}


STATE_LABELS = {"needs_writing": "Needs writing", "needs_updating": "Needs updating",
                "needs_signature": "Needs signature", "complete": "Complete"}


def load_coverage():
    spec = importlib.util.spec_from_file_location("coverage_report", ROOT / "scripts" / "coverage-report.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def field(text, key):
    m = re.search(rf"^{key}:\s*[\"']?([^\"'\n]*)", text[:3000], re.M)
    return m.group(1).strip() if m else ""


def main():
    data = json.loads((ROOT / "scripts" / "data" / "jurisdictions.json").read_text())
    coverage = load_coverage()
    states = {r["code"]: r["state"] for r in coverage.build_report()["rows"]}
    rows = {k: [] for k, _ in REGIONS}
    for j in data:
        pack = ROOT / j.get("dir", "")
        if str(j.get("dir", "")).startswith("skills/us/") or not pack.is_dir():
            continue
        files = [f for f in pack.glob("*.md") if not f.name.lower().startswith("readme")]
        if not files or j.get("region") not in rows:
            continue
        texts = [f.read_text(errors="ignore") for f in files]
        current = sum(field(t, "tax_year") == YEAR for t in texts)
        signed = sum(field(t, "tier") == "1" for t in texts)
        rows[j["region"]].append((NAMES.get(j["code"], j["name"].removesuffix(" (Canada)")), pack.relative_to(SKILLS).as_posix(),
                                  len(files), current, signed, OWNERS.get(j.get("owner"), ""), states[j["code"]]))
    total = sum(len(v) for v in rows.values())
    out = ["# Countries", "",
           f"{total} country packs. Open a country to see which skill covers which tax, and what is still missing.",
           f"Owners drive a region's packs: see [OWNERS.md](../docs/OWNERS.md). \"On {YEAR}\" counts skills on the current "
           "tax year. State is the next job a pack needs: Needs writing (a required domain is missing), Needs updating "
           "(a required skill is on an old or missing tax year), Needs signature (current, not all Accountant-reviewed), "
           "Complete. This page is generated by `scripts/build-country-index.py`.", ""]
    out += [" · ".join(f"[{label}](#{label.lower().replace(' ', '-')})" for _, label in REGIONS), ""]
    for key, label in REGIONS:
        owners = sorted({r[5] for r in rows[key] if r[5]})
        out += [f"## {label}", "", f"Owner: {', '.join(owners)}", "",
                f"| Country | State | Skills | On {YEAR} | Accountant-reviewed |", "|---|---|---:|---:|---:|"]
        for name, folder, n, cur, signed, _, state in sorted(rows[key]):
            out.append(f"| [{name}]({folder}/) | {STATE_LABELS[state]} | {n} | {cur} | {signed} |")
        out.append("")
    (SKILLS / "COUNTRIES.md").write_text("\n".join(out))
    print(f"{total} countries")
    counts = collections.Counter(r[6] for v in rows.values() for r in v)
    for state in coverage.STATES:
        print(f"  {state:<16} {counts[state]}")


if __name__ == "__main__":
    main()
